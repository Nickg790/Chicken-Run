  var PAD = 8; // rows below 0 we still generate (start runway)

  var World = {
    seed: 0,
    rng: null,
    lanes: [],
    runType: null,
    runLeft: 0,
    lastHazard: false,
    lastRailRow: -99,
    hazardStreak: 0,
    padCorridor: null,

    reset: function (seedStr) {
      this.seed = hashString(String(seedStr));
      this.rng = mulberry32(this.seed);
      this.lanes = [];
      this.runType = null;
      this.runLeft = 0;
      this.lastHazard = false;
      this.lastRailRow = -99;
      this.hazardStreak = 0;
      this.padCorridor = null;
      this.ensure(CFG.SAFE_ROWS + 20);
    },

    ensure: function (upToRow) {
      while (this.lanes.length <= upToRow + PAD) {
        var row = this.lanes.length - PAD;
        this.lanes.push(this.generate(row));
      }
    },

    get: function (row) {
      this.ensure(row + 12);
      var idx = row + PAD;
      if (idx < 0) idx = 0;
      return this.lanes[idx];
    },

    pickType: function (row) {
      var r = this.rng();
      // A hazard block is usually followed by a breather of grass.
      if (this.lastHazard && r < 0.40) return 'grass';
      if (r < 0.40) return 'road';
      if (r < 0.68) return 'grass';
      if (r < 0.88) return 'river';
      // Railways need elbow room. Left unchecked the run-length picker can
      // stack seven tracks into one screen, which is both a wall of crossing
      // signals and a stretch you simply cannot cross.
      if (row - this.lastRailRow < 6) return this.rng() < 0.5 ? 'grass' : 'road';
      return 'rail';
    },

    generate: function (row) {
      var rng = this.rng;
      var type;

      // The map is endless — a run ends by CASHOUT or DEATH, never by a line.
      if (row < CFG.SAFE_ROWS) {
        type = 'grass';
      } else if (this.hazardStreak >= CFG.MAX_HAZARD_RUN) {
        // Hard ceiling on unbroken danger. Run-lengths alone can chain river
        // into river into river until thirteen of the fourteen rows on screen
        // are water — technically survivable, actually miserable.
        this.runType = 'grass';
        this.runLeft = 1 + ((rng() * 2) | 0);
        type = 'grass';
        this.runLeft--;
        this.lastHazard = false;
      } else {
        if (this.runLeft <= 0) {
          this.runType = this.pickType(row);
          if (this.runType === 'grass') this.runLeft = 1 + ((rng() * 2) | 0);
          else if (this.runType === 'road') this.runLeft = 1 + ((rng() * 3) | 0);
          else if (this.runType === 'river') this.runLeft = 1 + ((rng() * 3) | 0);
          else this.runLeft = 1 + ((rng() * 2) | 0);
          this.lastHazard = this.runType !== 'grass';
        }
        type = this.runType;
        this.runLeft--;
      }

      this.hazardStreak = (type === 'grass') ? 0 : this.hazardStreak + 1;

      if (type === 'grass') return this.makeGrass(row);
      if (type === 'road') return this.makeRoad(row);
      if (type === 'river') return this.makeRiver(row);
      this.lastRailRow = row;
      return this.makeRail(row);
    },

    makeGrass: function (row) {
      var rng = this.rng;
      var lane = { row: row, type: 'grass', shade: row & 1, trees: {} };
      var startZone = row < CFG.SAFE_ROWS;
      var treeChance = startZone ? 0.04 : 0.15;
      var open = 0;

      for (var x = CFG.MIN_X; x <= CFG.MAX_X; x++) {
        var protectedTile = startZone && Math.abs(x) <= 1;
        if (!protectedTile && rng() < treeChance) {
          // Rocks and trees are the same thing to the game — a blocked tile.
          // Splitting them only varies the sprite, so density is unchanged.
          lane.trees[x] = { s: 0.95 + rng() * 0.35, rock: rng() < 0.26 };
        } else {
          open++;
        }
      }
      // Never let a row wall itself off.
      if (open < 4) lane.trees = {};
      return lane;
    },

    makeRoad: function (row) {
      var rng = this.rng;
      var kind = rng();
      var vType, len, speed, colors;
      // Traffic is deliberately unhurried — the tension is supposed to come
      // from deciding when to cash out, not from twitch reflexes.
      if (kind < 0.58) {
        vType = 'car';   len = 1.55; speed = 1.65 + rng() * 1.05; colors = CAR_COLORS;
      } else if (kind < 0.84) {
        vType = 'truck'; len = 2.55; speed = 1.30 + rng() * 0.70; colors = TRUCK_COLORS;
      } else {
        vType = 'bus';   len = 3.15; speed = 1.05 + rng() * 0.55; colors = BUS_COLORS;
      }

      var dir = rng() < 0.5 ? 1 : -1;
      var gap = len + 3.4 + rng() * 4.0;
      var span = Math.max(CFG.SPAWN_R - CFG.SPAWN_L, gap * 2);
      var count = Math.max(2, Math.ceil(span / gap));
      span = count * gap;

      var items = [];
      for (var i = 0; i < count; i++) items.push({ color: colors[(rng() * colors.length) | 0] });

      return {
        row: row, type: 'road', shade: row & 1, vType: vType,
        dir: dir, speed: speed, len: len, gap: gap, span: span,
        offset: rng() * span, items: items
      };
    },

    makeRiver: function (row) {
      var rng = this.rng;

      // A river lane is EITHER drifting logs or static lily pads — never both.
      // Pads can't fill the gaps of a log lane because those gaps move with the
      // logs, so a fixed pad would spend half its life underneath one.
      if (rng() < 0.42) return this.makePadRiver(row);

      var dir = rng() < 0.5 ? 1 : -1;
      var speed = 0.9 + rng() * 1.35;
      var gap = 4.0 + rng() * 4.2;
      var span = Math.max(CFG.SPAWN_R - CFG.SPAWN_L, gap * 2);
      var count = Math.max(2, Math.ceil(span / gap));
      span = count * gap;

      var items = [];
      for (var i = 0; i < count; i++) {
        items.push({ len: 2 + Math.floor(rng() * 3) + (rng() < 0.3 ? 0.5 : 0) });
      }
      return {
        row: row, type: 'river', mode: 'logs', dir: dir, speed: speed,
        gap: gap, span: span, offset: rng() * span, items: items, pads: null
      };
    },

    /**
     * Stepping-stone river: lily pads sit still and hold your weight.
     * A 3-wide corridor that drifts by at most one column per lane guarantees
     * consecutive pad lanes always overlap, so a crossing always exists.
     */
    makePadRiver: function (row) {
      var rng = this.rng;
      if (this.padCorridor === null) {
        this.padCorridor = ((rng() * 5) | 0) - 2;
      } else {
        this.padCorridor = clamp(this.padCorridor + (((rng() * 3) | 0) - 1),
                                 CFG.MIN_X + 1, CFG.MAX_X - 1);
      }

      var pads = {};
      var mk = function () {
        return { r: 0.92 + rng() * 0.38, a: rng() * Math.PI * 2, flower: rng() < 0.18 };
      };
      for (var d = -1; d <= 1; d++) pads[this.padCorridor + d] = mk();
      for (var x = CFG.MIN_X; x <= CFG.MAX_X; x++) {
        if (!pads[x] && rng() < 0.30) pads[x] = mk();
      }

      return {
        row: row, type: 'river', mode: 'pads',
        dir: rng() < 0.5 ? 1 : -1,     // visual ripple direction only
        speed: 0.30,                   // visual ripple speed only
        gap: 0, span: 1, offset: 0,
        items: [], pads: pads
      };
    },

    makeRail: function (row) {
      var rng = this.rng;
      return {
        row: row, type: 'rail',
        dir: rng() < 0.5 ? 1 : -1,
        period: 4.6 + rng() * 3.2,
        phase: rng() * 8
      };
    }
  };

  /* ---------------------------------------------------------------------- */
  /* Obstacle position math — pure functions of match time                   */
  /* ---------------------------------------------------------------------- */

  function wrapX(v, span) { return mod(v - CFG.SPAWN_L, span) + CFG.SPAWN_L; }

  /** Centre x of moving item i on a road/river lane at match time t. */
  function itemX(lane, i, t) {
    return wrapX(lane.offset + i * lane.gap + lane.dir * lane.speed * t, lane.span);
  }

  /** Train state for a rail lane: {warn, active, head, tail}. */
  function trainState(lane, t) {
    var tc = mod(t + lane.phase, lane.period);
    var warn = tc < CFG.TRAIN_WARN;
    var out = { warn: warn, active: false, head: 0, tail: 0, blink: (tc * 6.5) % 1 < 0.5 };
    if (tc >= CFG.TRAIN_WARN && tc < CFG.TRAIN_WARN + CFG.TRAIN_SWEEP) {
      var p = (tc - CFG.TRAIN_WARN) / CFG.TRAIN_SWEEP;
      var travel = (CFG.SPAWN_R - CFG.SPAWN_L) + CFG.TRAIN_LEN * 2;
      out.active = true;
      if (lane.dir > 0) {
        out.head = CFG.SPAWN_L - CFG.TRAIN_LEN + p * travel;
        out.tail = out.head - CFG.TRAIN_LEN;
      } else {
        out.head = CFG.SPAWN_R + CFG.TRAIN_LEN - p * travel;
        out.tail = out.head + CFG.TRAIN_LEN;
      }
    }
    return out;
  }

  /**
   * Whatever is holding the player up on a river lane, or null if that's open
   * water. Logs drift and carry you; lily pads are fixed and don't.
   */
  function platformUnder(lane, x, t) {
    if (lane.mode === 'pads') {
      var xi = Math.round(x);
      return lane.pads[xi] ? { pad: true, cx: xi } : null;
    }
    for (var i = 0; i < lane.items.length; i++) {
      var cx = itemX(lane, i, t);
      var half = lane.items[i].len / 2;
      if (x >= cx - half - 0.28 && x <= cx + half + 0.28) {
        return { pad: false, i: i, cx: cx, len: lane.items[i].len };
      }
    }
    return null;
  }

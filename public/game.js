  /**
   * The whole playfield is drawn axis-aligned and then tilted as one unit, so
   * every gameplay calculation stays in clean tile space while the picture
   * reads as an angled isometric board. sx()/sy() give "board space"; toScreen()
   * maps that to final pixels for anything that must NOT tilt (text, signals).
   */
  function applyWorldTilt() {
    var cx = View.w / 2, cy = View.h * CFG.PLAYER_SCREEN_Y;
    ctx.translate(cx, cy);
    ctx.rotate(CFG.WORLD_ANGLE);
    ctx.scale(1, CFG.WORLD_SQUASH);
    ctx.translate(-cx, -cy);
  }

  function toScreen(px, py) {
    var cx = View.w / 2, cy = View.h * CFG.PLAYER_SCREEN_Y;
    var dx = px - cx, dy = (py - cy) * CFG.WORLD_SQUASH;
    var c = Math.cos(CFG.WORLD_ANGLE), s = Math.sin(CFG.WORLD_ANGLE);
    return { x: cx + dx * c - dy * s, y: cy + dx * s + dy * c };
  }

  /** Where a lane's centreline crosses a given final-screen x. */
  function laneEdgePoint(row, screenX) {
    var cx = View.w / 2, cy = View.h * CFG.PLAYER_SCREEN_Y;
    var c = Math.cos(CFG.WORLD_ANGLE), s = Math.sin(CFG.WORLD_ANGLE);
    var dy = (sy(row) - cy) * CFG.WORLD_SQUASH;
    var dx = (screenX - cx + dy * s) / c;
    return { x: screenX, y: cy + dx * s + dy * c };
  }

  function shade(hex, f) {
    var n = parseInt(hex.slice(1), 16);
    var r = Math.round(clamp(((n >> 16) & 255) * f, 0, 255));
    var g = Math.round(clamp(((n >> 8) & 255) * f, 0, 255));
    var b = Math.round(clamp((n & 255) * f, 0, 255));
    return 'rgb(' + r + ',' + g + ',' + b + ')';
  }

  function drawShadow(cx, cy, rx, ry, a) {
    ctx.fillStyle = 'rgba(20,40,30,' + (a || 0.18) + ')';
    ellipse(ctx, cx, cy, rx, ry);
    ctx.fill();
  }

  /** The cartoon ink line every prop in the reference carries. */
  function ink(T) {
    ctx.lineWidth = Math.max(1.2, T * 0.032);
    ctx.strokeStyle = PAL.ink;
    ctx.lineJoin = 'round';
  }

  function offView(cx) { return cx < View.cullL || cx > View.cullR; }

  /**
   * The board tilt squashes rows to fake a camera above and behind. Ground
   * markings should compress with it, but anything STANDING on the ground —
   * a car, a tree, the chicken — must not, or it reads as a flat sticker.
   * Draw those inside upright(): it pre-stretches by 1/squash about the
   * object's ground point so the global squash lands it back at true height.
   */
  function upright(gx, gy, fn) {
    var k = 1 / CFG.WORLD_SQUASH;
    ctx.save();
    ctx.translate(gx, gy);
    ctx.scale(1, k);
    ctx.translate(-gx, -gy);
    fn();
    ctx.restore();
  }


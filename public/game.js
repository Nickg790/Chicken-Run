  function resize() {
    var vv = window.visualViewport;
    var w = Math.round((vv && vv.width) || window.innerWidth);
    var h = Math.round((vv && vv.height) || window.innerHeight);
    // iPhone 16 / 16 Pro are 3x displays. Capping below 3 makes the canvas
    // resample and softens every edge on the exact devices this ships to, and
    // the board is flat fills the A18 eats for breakfast — so render native.
    var dpr = Math.min(window.devicePixelRatio || 1, 3);

    View.w = w; View.h = h; View.dpr = dpr;
    canvas.width = Math.round(w * dpr);
    canvas.height = Math.round(h * dpr);
    canvas.style.width = w + 'px';
    canvas.style.height = h + 'px';
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.imageSmoothingEnabled = true;

    // Fit the requested column count, but keep tiles sane on tall/wide screens.
    View.tile = clamp(w / CFG.VIEW_COLS, 24, Math.max(32, h / 10));

    // Rotating the board sweeps its corners outside the viewport. The pivot is
    // the player's screen position, NOT the centre, so the top corners swing
    // further than a centred bounding box would suggest — pad from the pivot.
    var a = Math.abs(CFG.WORLD_ANGLE);
    var ca = Math.cos(a), sa = Math.sin(a);
    var py = h * CFG.PLAYER_SCREEN_Y;
    var reachX = 0, reachY = 0;
    [[-w / 2, -py], [w / 2, -py], [-w / 2, h - py], [w / 2, h - py]].forEach(function (c) {
      var dx = Math.abs(c[0]), dy = Math.abs(c[1]) / CFG.WORLD_SQUASH;
      reachX = Math.max(reachX, dx * ca + dy * sa);
      reachY = Math.max(reachY, dx * sa + dy * ca);
    });
    View.padX = Math.ceil(reachX - w / 2) + 12;
    View.padY = Math.ceil(reachY - Math.max(py, h - py)) + 12;
    View.cullL = -View.padX - View.tile * 3;
    View.cullR = w + View.padX + View.tile * 3;
  }


  function drawLaneBand(lane, row) {
    var T = View.tile;
    var y = sy(row) - T / 2;
    var x0 = -View.padX;
    var w = View.w + View.padX * 2;
    var behind = World.get(row + 1);   // the lane further up the screen

    if (lane.type === 'grass') {
      ctx.fillStyle = lane.shade ? PAL.grassA : PAL.grassB;
      ctx.fillRect(x0, y, w, T + 1);
    } else if (lane.type === 'road') {
      ctx.fillStyle = lane.shade ? PAL.road : PAL.roadB;
      ctx.fillRect(x0, y, w, T + 1);
      // Kerb shadow under the lane behind, kerb highlight at the near edge
      ctx.fillStyle = 'rgba(0,0,0,0.16)';
      ctx.fillRect(x0, y, w, T * 0.07);
      ctx.fillStyle = PAL.roadEdge;
      ctx.fillRect(x0, y + T - T * 0.05, w, T * 0.05);
      // White dashes down the middle
      ctx.save();
      ctx.strokeStyle = 'rgba(255,255,255,0.85)';
      ctx.lineWidth = Math.max(2, T * 0.05);
      ctx.lineCap = 'round';
      ctx.setLineDash([T * 0.42, T * 0.44]);
      ctx.lineDashOffset = -sx(0) % (T * 0.86);
      ctx.beginPath();
      ctx.moveTo(x0, y + T / 2);
      ctx.lineTo(x0 + w, y + T / 2);
      ctx.stroke();
      ctx.restore();
    } else if (lane.type === 'rail') {
      ctx.fillStyle = PAL.ballast;
      ctx.fillRect(x0, y, w, T + 1);
      ctx.fillStyle = 'rgba(0,0,0,0.14)';
      ctx.fillRect(x0, y, w, T * 0.07);
      // Sleepers sit on the WORLD grid, not the screen. Laying them out with a
      // screen-space modulo made them crawl sideways against the rails as the
      // camera panned; on a high-contrast repeating stripe that reads as a
      // moire shimmer, which is what makes the tracks painful to look at.
      // Anchored to world x they simply translate with everything else.
      ctx.fillStyle = PAL.tie;
      var TIE = 0.58;                                   // world tiles per sleeper
      var wLeft = (x0 - View.w / 2) / T + Game.cam.x;
      var wRight = (x0 + w - View.w / 2) / T + Game.cam.x;
      var tieW = T * TIE * 0.54;
      for (var ti = Math.floor(wLeft / TIE); ti <= Math.ceil(wRight / TIE); ti++) {
        rr(ctx, sx(ti * TIE) - tieW / 2, y + T * 0.17, tieW, T * 0.66, T * 0.03);
        ctx.fill();
      }
      // Rails: dark seat, steel head, bright top highlight
      [0.27, 0.64].forEach(function (f) {
        ctx.fillStyle = 'rgba(0,0,0,0.28)';
        ctx.fillRect(x0, y + T * f + T * 0.055, w, Math.max(1.5, T * 0.030));
        ctx.fillStyle = PAL.steel;
        ctx.fillRect(x0, y + T * f, w, Math.max(2, T * 0.070));
        ctx.fillStyle = 'rgba(255,255,255,0.55)';
        ctx.fillRect(x0, y + T * f, w, Math.max(1, T * 0.022));
      });
    } else if (lane.type === 'river') {
      ctx.fillStyle = PAL.water;
      ctx.fillRect(x0, y, w, T + 1);
      // Streaks of foam drifting with the current
      ctx.fillStyle = 'rgba(255,255,255,0.28)';
      var ww = T * 2.4;
      var drift = mod(Game.t * lane.speed * lane.dir * T * 0.5 + row * 37, ww);
      for (var wx = x0 - ww + drift; wx < x0 + w + ww; wx += ww) {
        rr(ctx, wx, y + T * 0.30, ww * 0.34, T * 0.055, T * 0.03); ctx.fill();
        rr(ctx, wx + ww * 0.48, y + T * 0.64, ww * 0.20, T * 0.05, T * 0.03); ctx.fill();
      }
      // The lane behind is a raised slab: its earthen face drops into the water.
      if (behind.type !== 'river') {
        ctx.fillStyle = PAL.bank;
        ctx.fillRect(x0, y, w, T * 0.16);
        ctx.fillStyle = PAL.bankDark;
        ctx.fillRect(x0, y + T * 0.16, w, T * 0.04);
        ctx.fillStyle = PAL.waterDeep;
        ctx.fillRect(x0, y + T * 0.20, w, T * 0.10);
      } else {
        ctx.fillStyle = PAL.waterDeep;
        ctx.fillRect(x0, y, w, T * 0.08);
      }
    }

    // Grass meeting a lower lane in front: the near edge gets a lip so lanes
    // read as stacked slabs rather than painted stripes.
    if (lane.type === 'grass') {
      var front = World.get(row - 1);
      if (front.type === 'river') {
        ctx.fillStyle = PAL.grassEdge;
        ctx.fillRect(x0, y + T - T * 0.06, w, T * 0.06);
      } else if (front.type !== 'grass') {
        ctx.fillStyle = 'rgba(0,0,0,0.10)';
        ctx.fillRect(x0, y + T - T * 0.03, w, T * 0.03);
      }
      if (behind.type !== 'grass' && behind.type !== 'river') {
        ctx.fillStyle = 'rgba(0,0,0,0.10)';
        ctx.fillRect(x0, y, w, T * 0.05);
      }
    }

    // Cap the playable strip with hedge on both sides. The tilt widens the
    // visible band well past the screen, so these fills run into the padding.
    var edgeL = sx(CFG.MIN_X - 2.5);
    var edgeR = sx(CFG.MAX_X + 2.5);
    if (edgeL > x0) {
      ctx.fillStyle = PAL.bush;
      ctx.fillRect(x0, y, edgeL - x0, T + 1);
      ctx.fillStyle = 'rgba(0,0,0,0.16)';
      ctx.fillRect(edgeL - T * 0.06, y, T * 0.06, T + 1);
    }
    if (edgeR < x0 + w) {
      ctx.fillStyle = PAL.bush;
      ctx.fillRect(edgeR, y, x0 + w - edgeR, T + 1);
      ctx.fillStyle = 'rgba(0,0,0,0.16)';
      ctx.fillRect(edgeR, y, T * 0.06, T + 1);
    }
  }


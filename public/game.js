  /* Update                                                                  */
  /* ====================================================================== */

  function update(dt) {
    if (Game.phase === 'countdown' || Game.phase === 'playing' || Game.phase === 'resolved') {
      Game.t = Math.max(0, (Net.now() - Game.startAt) / 1000);
    }

    if (Game.phase === 'countdown' && Net.now() >= Game.startAt) {
      Game.phase = 'playing';
      UI.hideCountdown();
      UI.refreshCashout();
    }

    if (Player.death) Player.death.t += dt;
    if (Player.squash > 0) Player.squash = Math.max(0, Player.squash - dt * 7);
    if (Game.shake > 0) Game.shake = Math.max(0, Game.shake - dt * 4.5);
    Popups.update(dt);

    if (Player.hopping) {
      Player.hopT += dt * (1000 / CFG.HOP_MS);
      if (Player.hopT >= 1) {
        Player.hopT = 1;
        landed();
        if (Player.queued && Player.isRunning()) {
          var q = Player.queued; Player.queued = null;
          tryMove(q.dx, q.dy);
        }
      } else {
        var e = Player.hopT;
        Player.fx = lerp(Player.fromX, Player.toX, e);
        Player.frow = lerp(Player.fromRow, Player.toRow, e);
      }
    } else {
      Player.fx = Player.x;
      Player.frow = Player.row;
    }

    if (Game.phase === 'playing') collisionCheck(dt);

    // Train proximity callout — one per approaching train.
    if (Game.phase === 'playing' && Player.isRunning()) {
      for (var r = Math.round(Player.row) + 1; r <= Math.round(Player.row) + 3; r++) {
        var ln = World.get(r);
        if (ln.type !== 'rail') continue;
        var st = trainState(ln, Game.t);
        var key = r + ':' + Math.floor((Game.t + ln.phase) / ln.period);
        if (st.warn && !Game.trainAlerted[key]) {
          Game.trainAlerted[key] = true;
          Popups.add('TRAIN', PAL.crimson, { size: 0.30, vy: 1.1, centre: true, life: 0.8 });
          Game.shake = Math.max(Game.shake, 0.2);
        }
      }
    }

    // Camera — smooth follow with a little look-ahead. Once your run is
    // resolved the camera drifts to the rival so you can sweat their attempt.
    if (Game.phase !== 'menu') {
      var followRow = Player.frow, followX = Player.fx;
      if (!Game.solo && Game.phase === 'resolved' &&
          Game.t - Game.resolveAt > 1.1 &&
          Game.ghost.active && Game.ghost.status === 'running' &&
          !Game.ghost.deadHidden) {          // never drift off to watch a frozen rival
        followRow = Game.ghost.frow;
        followX = Game.ghost.fx;
        if (!Game.spectating) {
          Game.spectating = true;
          UI.toast(Player.status === 'banked' ? 'BANKED — WATCHING RIVAL' : 'WATCHING RIVAL');
        }
      }
      var targetRow = followRow + 0.35;
      var camReach = Math.max(0, CFG.MAX_X - (View.w / 2) / View.tile + 0.9);
      var targetX = clamp(followX, -camReach, camReach);
      var k = 1 - Math.pow(0.0016, dt);
      Game.cam.row = lerp(Game.cam.row, targetRow, k);
      Game.cam.x = lerp(Game.cam.x, targetX, k);
    }

    // Ghost interpolation.
    var g = Game.ghost;
    if (g.active) {
      var gk = 1 - Math.pow(0.0009, dt);
      g.fx = lerp(g.fx, g.x, gk);
      g.frow = lerp(g.frow, g.row, gk);
    }

    UI.tick();
  }

  var rafId = 0;
  function loop(now) {
    rafId = requestAnimationFrame(loop);
    var dt = Game.lastFrame ? Math.min(0.05, (now - Game.lastFrame) / 1000) : 0.016;
    Game.lastFrame = now;
    update(dt);
    render();
  }


  var Popups = {
    list: [],

    add: function (text, color, opts) {
      opts = opts || {};
      this.list.push({
        text: text,
        color: color || '#fff',
        t: 0,
        life: opts.life || 0.95,
        size: opts.size || 0.36,       // multiple of tile size
        vy: opts.vy || 1.5,            // tiles per second upward
        drift: (Math.random() - 0.5) * 0.5,
        worldX: opts.worldX == null ? Player.fx : opts.worldX,
        worldRow: opts.worldRow == null ? Player.frow : opts.worldRow,
        centre: !!opts.centre
      });
      if (this.list.length > 24) this.list.shift();
    },

    update: function (dt) {
      for (var i = this.list.length - 1; i >= 0; i--) {
        var p = this.list[i];
        p.t += dt;
        if (p.t >= p.life) this.list.splice(i, 1);
      }
    },

    clear: function () { this.list.length = 0; },

    draw: function (ctx, View) {
      var T = View.tile;
      for (var i = 0; i < this.list.length; i++) {
        var p = this.list[i];
        var k = p.t / p.life;
        var rise = easeOutCubic(k) * p.vy * T;
        var alpha = k < 0.12 ? (k / 0.12) : (1 - Math.pow((k - 0.12) / 0.88, 2));
        var scale = k < 0.16 ? lerp(0.6, 1.12, k / 0.16) : lerp(1.12, 1, Math.min(1, (k - 0.16) / 0.3));

        var x, y;
        if (p.centre) {
          x = View.w / 2;
          y = View.h * 0.34 - rise;
        } else {
          // Popups live in screen space but track a board position, so the
          // anchor has to go through the same tilt the board does.
          var a = toScreen(sx(p.worldX + p.drift * k), sy(p.worldRow));
          x = a.x;
          y = a.y - T * 0.75 - rise;
        }

        ctx.save();
        ctx.globalAlpha = clamp(alpha, 0, 1);
        ctx.translate(x, y);
        ctx.scale(scale, scale);
        ctx.font = '900 ' + Math.round(T * p.size) + 'px ' + FONT;
        ctx.textAlign = 'center';
        ctx.textBaseline = 'middle';
        ctx.lineWidth = Math.max(2, T * 0.05);
        ctx.strokeStyle = 'rgba(6,10,16,0.8)';
        ctx.strokeText(p.text, 0, 0);
        ctx.fillStyle = p.color;
        ctx.shadowColor = p.color;
        ctx.shadowBlur = T * 0.16;
        ctx.fillText(p.text, 0, 0);
        ctx.restore();
      }
    }
  };


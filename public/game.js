/* ==========================================================================
   Chicken Run — client
   Canvas renderer + deterministic tile engine + hop physics + touch controls
   + cashout scoring + Socket.io match sync.

   Determinism contract with the server:
     The server hands both clients the same `seed` and a `startAt` timestamp on
     the shared (clock-synced) timeline. Lanes are generated by a seeded PRNG in
     strict row order, and every moving obstacle's position is a pure function
     of match time t. Both players race a byte-identical map, while only a few
     numbers per player cross the wire at 20 Hz.

   Scoring contract:
     Everything you earn is PENDING and at risk. CASHOUT banks it and ends your
     run. DEATH forfeits all of it — nothing is ever auto-saved on death.
     Players never collide with each other; the rival is a ghost, not a body.
   ========================================================================== */

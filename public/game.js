  function drawPlayer() {
    var T = View.tile;
    var cx = sx(Player.fx);
    var groundY = sy(Player.frow);
    var size = T * 0.86;

    if (Player.death) { drawDeath(cx, groundY, size); return; }

    var hop = Player.hopping ? Math.sin(Math.PI * Player.hopT) : 0;
    var lift = hop * CFG.HOP_ARC * T;
    var stretch = Player.hopping ? (1 + hop * 0.16 - (1 - hop) * 0.10) : (1 - Player.squash * 0.26);
    var widen = Player.hopping ? (1 - hop * 0.10 + (1 - hop) * 0.08) : (1 + Player.squash * 0.24);

    drawShadow(cx, groundY + T * 0.26, T * 0.30 * (1 - hop * 0.3), T * 0.13 * (1 - hop * 0.3), 0.24);

    if (Player.status === 'banked') {
      ctx.save();
      ctx.globalAlpha = 0.45 + Math.sin(Game.t * 5) * 0.16;
      ctx.fillStyle = 'rgba(126,200,80,0.35)';
      ellipse(ctx, cx, groundY - T * 0.1, T * 0.58, T * 0.58); ctx.fill();
      ctx.restore();
    }

    drawChicken(cx, groundY - lift - T * 0.06, size, Player.dir, {
      sx: widen, sy: stretch, species: Player.species, body: Player.bodyColor
    });
  }

  function drawDeath(cx, cy, size) {
    var T = View.tile;
    var d = Player.death;
    var p = Math.min(1, d.t / 0.42);

    if (d.kind === 'splash') {
      var sink = easeOutCubic(p);
      ctx.save();
      ctx.globalAlpha = 1 - sink * 0.85;
      drawChicken(cx, cy - T * 0.05 + sink * T * 0.22, size * (1 - sink * 0.4), Player.dir,
        { species: Player.species, body: Player.bodyColor });
      ctx.restore();
      ctx.strokeStyle = 'rgba(255,255,255,' + (0.75 * (1 - p)) + ')';
      ctx.lineWidth = Math.max(1.5, T * 0.06);
      for (var i = 0; i < 3; i++) {
        var rp = clamp(p * 1.6 - i * 0.22, 0, 1);
        if (rp <= 0) continue;
        ellipse(ctx, cx, cy + T * 0.04, T * (0.16 + rp * 0.62), T * (0.06 + rp * 0.26));
        ctx.stroke();
      }
    } else if (d.kind === 'train') {
      var fly = easeOutCubic(p);
      var off = d.dir * fly * T * 5.5;
      ctx.save();
      ctx.globalAlpha = 1 - fly * 0.6;
      ctx.translate(cx + off, cy - T * 0.05 - Math.sin(p * Math.PI) * T * 1.4);
      ctx.rotate(fly * d.dir * 7);
      drawChicken(0, 0, size, Player.dir,
        { sy: 0.55, sx: 1.3, species: Player.species, body: Player.bodyColor });
      ctx.restore();
    } else {
      var f = easeOutCubic(p);
      drawShadow(cx, cy + T * 0.24, T * 0.34, T * 0.14, 0.3);
      drawChicken(cx, cy + f * T * 0.20 - T * 0.05, size, Player.dir, {
        sx: 1 + f * 0.75, sy: 1 - f * 0.80, species: Player.species, body: Player.bodyColor
      });
      ctx.fillStyle = 'rgba(255,255,255,' + (0.85 * (1 - p)) + ')';
      for (var k = 0; k < 5; k++) {
        var a = (k / 5) * Math.PI * 2 + 0.5;
        ellipse(ctx, cx + Math.cos(a) * T * p * 1.1, cy + Math.sin(a) * T * p * 0.6 - T * 0.2,
                T * 0.07, T * 0.10);
        ctx.fill();
      }
    }
  }

  function drawGhost() {
    var g = Game.ghost;
    if (!g.active || g.status === 'dead') return;
    var T = View.tile;
    ctx.save();
    ctx.globalAlpha = 0.40;
    drawShadow(sx(g.fx), sy(g.frow) + T * 0.26, T * 0.28, T * 0.12, 0.35);
    drawChicken(sx(g.fx), sy(g.frow) - T * 0.06, T * 0.86, 0,
      { species: g.species || 'chicken', body: g.bodyColor || '#ff9f43' });
    ctx.restore();
  }

  /** Ghost label + off-screen chevron, both drawn upright after the tilt. */
  function drawGhostOverlay() {
    var g = Game.ghost;
    if (!g.active || g.status === 'dead') return;
    var T = View.tile;
    var p = toScreen(sx(g.fx), sy(g.frow));

    // You sit at PLAYER_SCREEN_Y (0.70), so there is roughly three times as
    // much screen above you as below. Judging "gone from view" by fixed screen
    // edges meant a rival had to get ~9 rows AHEAD to raise the up arrow but
    // only ~3 rows BEHIND to raise the down one — so in practice only the
    // behind case ever appeared. Give both directions the same slack around
    // you instead: the lower edge is unchanged, the upper one comes down to
    // match it, and the gap now reads the same either way.
    var SLACK = 0.22;                        // screen heights either side of you
    var edgeAhead = View.h * (CFG.PLAYER_SCREEN_Y - SLACK);
    var edgeBehind = View.h * (CFG.PLAYER_SCREEN_Y + SLACK);

    if (p.y > edgeAhead && p.y < edgeBehind) {
      ctx.save();
      ctx.globalAlpha = 0.78;
      ctx.fillStyle = g.status === 'banked' ? PAL.neon : '#ff9f43';
      ctx.font = '900 ' + Math.round(T * 0.24) + 'px ' + FONT;
      ctx.textAlign = 'center';
      ctx.lineWidth = Math.max(2, T * 0.05);
      ctx.strokeStyle = 'rgba(6,10,16,0.6)';
      var label = g.status === 'banked' ? 'BANKED' : String(g.pending);
      ctx.strokeText(label, p.x, p.y - T * 0.82);
      ctx.fillText(label, p.x, p.y - T * 0.82);
      ctx.restore();
      return;
    }

    var ahead = p.y <= edgeAhead;
    var py = ahead ? View.h * 0.17 : View.h * 0.88;
    var delta = Math.round(g.frow - Player.frow);

    ctx.save();
    ctx.globalAlpha = 0.9;
    ctx.fillStyle = 'rgba(45,83,100,0.94)';
    rr(ctx, View.w / 2 - T * 1.4, py - T * 0.30, T * 2.8, T * 0.60, T * 0.30);
    ctx.fill();
    ctx.strokeStyle = '#f3ead8';
    ctx.lineWidth = 2;
    ctx.stroke();
    ctx.fillStyle = '#ffffff';
    ctx.font = '900 ' + Math.round(T * 0.24) + 'px ' + FONT;
    ctx.textAlign = 'center';
    ctx.textBaseline = 'middle';
    ctx.fillText((ahead ? '▲ ' : '▼ ') + Math.abs(delta) + ' ROWS', View.w / 2, py);
    ctx.restore();
  }


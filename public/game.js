  var Touch_ = { x: 0, y: 0, t: 0, id: null };
  var SWIPE_PX = 26;

  function onStart(x, y, id) {
    Touch_.x = x; Touch_.y = y; Touch_.t = performance.now(); Touch_.id = id;
    SFX.ensure(); // first gesture unlocks WebAudio on iOS
  }

  function onEnd(x, y) {
    var dx = x - Touch_.x;
    var dy = y - Touch_.y;
    var adx = Math.abs(dx), ady = Math.abs(dy);
    var dtms = performance.now() - Touch_.t;

    if (adx < SWIPE_PX && ady < SWIPE_PX) {
      if (dtms < 700) tryMove(0, 1);              // tap = hop forward
      return;
    }
    if (adx > ady) tryMove(dx > 0 ? 1 : -1, 0);   // swipe left / right
    else if (dy > 0) tryMove(0, -1);              // swipe down = back
    else tryMove(0, 1);                           // swipe up = forward
  }

  canvas.addEventListener('touchstart', function (e) {
    e.preventDefault();
    var t = e.changedTouches[0];
    if (Touch_.id !== null) return;
    onStart(t.clientX, t.clientY, t.identifier);
  }, { passive: false });

  canvas.addEventListener('touchmove', function (e) { e.preventDefault(); }, { passive: false });

  canvas.addEventListener('touchend', function (e) {
    e.preventDefault();
    for (var i = 0; i < e.changedTouches.length; i++) {
      var t = e.changedTouches[i];
      if (t.identifier === Touch_.id) { Touch_.id = null; onEnd(t.clientX, t.clientY); }
    }
  }, { passive: false });

  canvas.addEventListener('touchcancel', function () { Touch_.id = null; }, { passive: false });

  canvas.addEventListener('mousedown', function (e) { onStart(e.clientX, e.clientY, 'm'); });
  canvas.addEventListener('mouseup', function (e) {
    if (Touch_.id === 'm') { Touch_.id = null; onEnd(e.clientX, e.clientY); }
  });

  window.addEventListener('keydown', function (e) {
    var k = e.key;
    if (k === ' ' || k === 'Spacebar' || k === 'Enter') { e.preventDefault(); bankScore(); return; }
    if (k === 'ArrowUp' || k === 'w' || k === 'W') { e.preventDefault(); tryMove(0, 1); }
    else if (k === 'ArrowDown' || k === 's' || k === 'S') { e.preventDefault(); tryMove(0, -1); }
    else if (k === 'ArrowLeft' || k === 'a' || k === 'A') { e.preventDefault(); tryMove(-1, 0); }
    else if (k === 'ArrowRight' || k === 'd' || k === 'D') { e.preventDefault(); tryMove(1, 0); }
  });


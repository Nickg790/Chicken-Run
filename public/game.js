  var Net = {
    socket: null,
    offset: 0,
    samples: [],
    code: null,
    slot: 0,
    timer: 0,

    now: function () { return Date.now() + this.offset; },

    connect: function () {
      if (typeof io === 'undefined') { UI.setConn('OFFLINE — SOLO ONLY', false); return; }
      var self = this;

      // Render's free tier sleeps when idle; the first hit can take ~30s. Poke
      // the health route right away so the server is waking while the menu
      // loads, and say so instead of looking broken.
      try { fetch(SOCKET_URL + '/health', { mode: 'cors', cache: 'no-store' }).catch(function () {}); } catch (e) {}
      var slow = setTimeout(function () {
        if (!self.socket || !self.socket.connected) UI.setConn('WAKING SERVER… (~30S)', false);
      }, 2500);

      var s = io(SOCKET_URL, {
        transports: ['websocket', 'polling'],
        reconnectionDelayMax: 4000,
        timeout: 20000
      });
      this.socket = s;

      s.on('connect', function () { clearTimeout(slow); UI.setConn('ONLINE', true); self.syncClock(); });
      s.on('disconnect', function () { UI.setConn('RECONNECTING…', false); });
      s.on('connect_error', function () { UI.setConn('WAKING SERVER… RETRYING', false); });

      s.on('tsync', function (d) {
        var now = Date.now();
        var rtt = now - d.t0;
        self.samples.push(d.server + rtt / 2 - now);
        if (self.samples.length > 7) self.samples.shift();
        var sorted = self.samples.slice().sort(function (a, b) { return a - b; });
        self.offset = sorted[(sorted.length / 2) | 0];
      });

      s.on('room', function (room) { Net.code = room.code; UI.setLobbyCode(room.code); });
      s.on('matchStart', function (d) { Net.slot = d.you.slot; UI.beginMatch(d); });

      s.on('oppState', function (d) {
        var g = Game.ghost;
        if (!g.active) { g.fx = d.x; g.frow = d.y; g.active = true; }
        g.x = d.x; g.row = d.y; g.pending = d.p;
      });

      s.on('oppDied', function () {
        // Deliberately silent. Announcing that your rival is out mid-run ends
        // the match in spirit before it ends in fact: you know 0 already beats
        // them, so you bank on the spot and the last stretch — the part the
        // whole game is built around — never gets played.
        //
        // So nothing is shown. Their ghost and score simply stop updating
        // (their client stops streaming the moment they die), which leaves
        // them frozen at their last position looking like someone playing it
        // safe. Nothing false is drawn: that IS their last known state. The
        // truth lands on the results screen, from the server, as it always did.
        //
        // `status` deliberately stays 'running' — it is what the ghost and the
        // rival pill read from. `deadHidden` carries the truth for logic that
        // must not be fooled (see the spectate camera).
        Game.ghost.deadHidden = true;
      });

      s.on('oppCashout', function (d) {
        var g = Game.ghost;
        g.status = 'banked';
        g.banked = d.banked;
        UI.toast('RIVAL BANKED ' + d.banked);
        Popups.add('RIVAL BANKED ' + d.banked, PAL.crimson, { size: 0.34, vy: 1.0, centre: true, life: 1.3 });
      });

      s.on('matchEnd', function (d) { UI.showEnd(d); });
      s.on('rematchPending', function () { UI.toast('RIVAL WANTS A REMATCH'); });
      s.on('opponentLeft', function () { Game.ghost.active = false; UI.toast('RIVAL LEFT THE MATCH'); });
    },

    syncClock: function () {
      var self = this;
      for (var i = 0; i < 5; i++) {
        (function (n) {
          setTimeout(function () {
            if (self.socket && self.socket.connected) self.socket.emit('tsync', Date.now());
          }, n * 140);
        })(i);
      }
    },

    emit: function (ev, data) {
      if (Game.solo || !this.socket || !this.socket.connected) return;
      this.socket.emit(ev, data);
    },

    /** 20 Hz stream: tile x/y, pending score, running flag. */
    startStream: function () {
      var self = this;
      clearInterval(this.timer);
      if (Game.solo) return;
      this.timer = setInterval(function () { self.sendState(); }, 1000 / CFG.NET_HZ);
    },

    stopStream: function () { clearInterval(this.timer); this.timer = 0; },

    /** `pendingOverride` lets onDeath relay its pre-death score — see there. */
    sendState: function (force, pendingOverride) {
      if (Game.solo || !this.socket || !this.socket.connected) return;
      if (!force && Game.phase !== 'playing' && Game.phase !== 'countdown') return;
      this.socket.emit('state', {
        x: Math.round(Player.fx * 100) / 100,
        y: Math.round(Player.frow * 100) / 100,
        p: pendingOverride == null ? Player.pending : pendingOverride,
        a: Player.isRunning() ? 1 : 0
      });
    }
  };


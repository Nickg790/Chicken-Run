  /* Frame                                                                   */
  /* ====================================================================== */

  function render() {
    var T = View.tile;

    ctx.fillStyle = PAL.void;
    ctx.fillRect(0, 0, View.w, View.h);

    ctx.save();
    if (Game.shake > 0) {
      ctx.translate((Math.random() - 0.5) * Game.shake * T * 0.3,
                    (Math.random() - 0.5) * Game.shake * T * 0.3);
    }
    applyWorldTilt();

    var extra = Math.ceil(View.padY / T) + 2;
    var rowsUp = Math.ceil((View.h * CFG.PLAYER_SCREEN_Y) / T) + extra;
    var rowsDown = Math.ceil((View.h * (1 - CFG.PLAYER_SCREEN_Y)) / T) + extra;
    var topRow = Math.ceil(Game.cam.row) + rowsUp;
    var botRow = Math.floor(Game.cam.row) - rowsDown;
    World.ensure(topRow + 4);

    // Pass 1 — lane surfaces, far to near.
    for (var r = topRow; r >= botRow; r--) {
      if (r < -PAD) continue;
      drawLaneBand(World.get(r), r);
    }

    // Pass 2 — props and actors, far to near (painter's order), clipped to the
    // playable strip so traffic spawning off-world never draws on the hedge.
    var playerBucket = Math.round(Player.frow);
    var ghostBucket = Game.ghost.active ? Math.round(Game.ghost.frow) : null;
    var crossings = [];

    ctx.save();
    var clipL = sx(CFG.MIN_X - 2.5);
    var clipR = sx(CFG.MAX_X + 2.5);
    ctx.beginPath();
    ctx.rect(clipL, -View.padY - View.h, Math.max(0, clipR - clipL), View.h * 3 + View.padY * 2);
    ctx.clip();

    for (var row = topRow; row >= botRow; row--) {
      if (row < -PAD) continue;
      var lane = World.get(row);
      drawEdgeBushes(row);

      if (lane.type === 'grass') {
        for (var key in lane.trees) drawBlocker(+key, row, lane.trees[key]);
      } else if (lane.type === 'road') {
        for (var i = 0; i < lane.items.length; i++) {
          lane.itemColor = lane.items[i].color;
          drawVehicle(lane, sx(itemX(lane, i, Game.t)), row);
        }
      } else if (lane.type === 'river') {
        if (lane.pads) {
          for (var q in lane.pads) drawLilyPad(+q, row, lane.pads[q]);
        }
        for (var j = 0; j < lane.items.length; j++) {
          drawLog(sx(itemX(lane, j, Game.t)), row, lane.items[j].len);
        }
      } else if (lane.type === 'rail') {
        var st = trainState(lane, Game.t);
        crossings.push({ row: row, st: st });
        if (st.active) drawTrain(lane, row, st);
      }

      if (ghostBucket === row) drawGhost();
      if (playerBucket === row && Game.phase !== 'menu') drawPlayer();
    }

    if (ghostBucket === null || ghostBucket > topRow || ghostBucket < botRow) drawGhost();
    if (Game.phase !== 'menu' && (playerBucket > topRow || playerBucket < botRow)) drawPlayer();

    ctx.restore(); // release the playfield clip
    ctx.restore(); // release the world tilt

    // Screen-space layer: warning wash, signals, labels, popups.
    for (var wi = 0; wi < crossings.length; wi++) {
      drawCrossingWash(crossings[wi].row, crossings[wi].st);
    }
    // Show a post only where it carries information: any track that is warning
    // or occupied, plus the next track ahead.
    var nearest = null;
    for (var wj = 0; wj < crossings.length; wj++) {
      var cr = crossings[wj];
      if (cr.row < Player.frow) continue;
      if (nearest === null || cr.row < nearest.row) nearest = cr;
    }
    for (var wk = 0; wk < crossings.length; wk++) {
      var c2 = crossings[wk];
      if (c2.st.warn || c2.st.active || c2 === nearest) drawCrossing(c2.row, c2.st);
    }

    if (Game.phase !== 'menu') Popups.draw(ctx, View);
    drawGhostOverlay();
  }

  /** Red wash across a track that is about to be hit by a train. */
  function drawCrossingWash(row, st) {
    if (!st.warn || !st.blink) return;
    var T = View.tile;
    var a = laneEdgePoint(row, -View.w);
    var b = laneEdgePoint(row, View.w * 2);
    ctx.save();
    ctx.strokeStyle = 'rgba(255,45,45,0.16)';
    ctx.lineWidth = T * CFG.WORLD_SQUASH;
    ctx.beginPath();
    ctx.moveTo(a.x, a.y);
    ctx.lineTo(b.x, b.y);
    ctx.stroke();
    ctx.restore();
  }

  /* ====================================================================== */
  /* Movement + collision                                                    */
  /* ====================================================================== */

  function currentLane() { return World.get(Math.round(Player.row)); }

  function tryMove(dx, dy) {
    if (Game.phase !== 'playing' || !Player.isRunning()) return;

    if (Player.hopping) {
      // Buffer one input so fast tapping feels responsive rather than dropped.
      if (Player.hopT > 0.45) Player.queued = { dx: dx, dy: dy };
      return;
    }

    Player.dir = dy > 0 ? 0 : dy < 0 ? 2 : (dx > 0 ? 1 : 3);

    var lane = currentLane();
    var onDriftingLog = lane.type === 'river' && lane.mode === 'logs' && Player.onLog;
    var baseX = onDriftingLog ? Player.x : Math.round(Player.x);
    var targetRow = Math.round(Player.row) + dy;
    var targetX = baseX + dx;

    targetRow = Math.max(-2, targetRow);
    var destLane = World.get(targetRow);
    // Only a drifting-log lane keeps a fractional x; pads sit on whole columns.
    if (!(destLane.type === 'river' && destLane.mode === 'logs')) targetX = Math.round(targetX);
    targetX = clamp(targetX, CFG.MIN_X, CFG.MAX_X);

    // Trees are solid.
    if (destLane.type === 'grass' && destLane.trees[Math.round(targetX)]) return;

    Player.fromX = Player.x; Player.fromRow = Player.row;
    Player.toX = targetX; Player.toRow = targetRow;
    Player.hopping = true;
    Player.hopT = 0;
    Player.onLog = false;
    SFX.hop();
  }

  function landed() {
    Player.x = Player.toX;
    Player.row = Player.toRow;
    Player.fx = Player.x;
    Player.frow = Player.row;
    Player.hopping = false;
    Player.squash = 1;

    var lane = currentLane();

    // +1 per NEW forward tile (backtracking never re-scores).
    if (Player.row > Player.maxRow) {
      Player.pending += (Player.row - Player.maxRow) * CFG.TILE_POINTS;
      Player.maxRow = Player.row;
      UI.pulsePending();
    }

    // River landing must find a log or a lily pad.
    if (lane.type === 'river') {
      var lg = platformUnder(lane, Player.x, Game.t);
      if (!lg) { onDeath('splash'); return; }
      Player.onLog = true;
      if (lg.pad) Player.x = Player.fx = lg.cx;   // settle onto the pad
    }
  }

  function collisionCheck(dt) {
    if (!Player.isRunning()) return;
    var lane = currentLane();

    if (lane.type === 'road') {
      if (Player.hopping) return;                 // brief i-frames mid-hop
      for (var i = 0; i < lane.items.length; i++) {
        var cx = itemX(lane, i, Game.t);
        var d = Math.abs(Player.x - cx);
        if (d < lane.len / 2 + 0.40) { onDeath('squash'); return; }
        // Near miss: it got close enough to ruffle feathers but didn't hit.
        var nkey = lane.row + ':' + i;
        if (d < lane.len / 2 + CFG.NEAR_MISS) {
          if (!Game.nearFlags[nkey]) {
            // A near miss is felt, not announced — a shove of the camera and a
            // low thrum. No text: this fires often and would read as clutter.
            Game.nearFlags[nkey] = true;
            Game.shake = Math.max(Game.shake, 0.45);
            SFX.near();
          }
        } else if (d > lane.len / 2 + CFG.NEAR_MISS * 1.8) {
          Game.nearFlags[nkey] = false;
        }
      }
    } else if (lane.type === 'rail') {
      var st = trainState(lane, Game.t);
      if (st.active) {
        var a = Math.min(st.head, st.tail), b = Math.max(st.head, st.tail);
        if (Player.x > a - 0.4 && Player.x < b + 0.4) { onDeath('train', lane.dir); return; }
      }
    } else if (lane.type === 'river' && !Player.hopping) {
      var lg = platformUnder(lane, Player.x, Game.t);
      if (!lg) { onDeath('splash'); return; }
      Player.onLog = true;
      // A log carries you at exactly its speed; a lily pad is anchored, so
      // standing on one is a genuine safe pause in the middle of the water.
      if (!lg.pad) {
        Player.x += lane.dir * lane.speed * dt;
        Player.fx = Player.x;
        if (Player.x < CFG.MIN_X - 0.9 || Player.x > CFG.MAX_X + 0.9) { onDeath('splash'); return; }
      }
    }
  }

  /* ====================================================================== */
  /* Run resolution — the whole game lives here                              */
  /* ====================================================================== */

  /**
   * DEATH. Everything pending is forfeit. Nothing is ever auto-saved here:
   * a dead run banks exactly 0.
   */
  function onDeath(kind, dir) {
    if (!Player.isRunning()) return;
    var lost = Player.pending;

    Player.pending = 0;
    Player.banked = 0;
    Player.status = 'dead';
    Player.hopping = false;
    Player.queued = null;
    Player.death = { kind: kind, t: 0, dir: dir || 1 };

    Game.shake = kind === 'train' ? 1.6 : kind === 'squash' ? 1.2 : 0.5;
    Game.phase = 'resolved';
    Game.resolveAt = Game.t;

    Popups.add(lost > 0 ? 'WIPED OUT  —  ' + lost + ' LOST' : 'WIPED OUT',
               PAL.crimson, { size: 0.40, vy: 1.0, centre: true, life: 1.3 });
    SFX.death();
    if (navigator.vibrate) { try { navigator.vibrate(kind === 'splash' ? 40 : [0, 60, 40, 90]); } catch (e) {} }

    // Send the score they had a moment ago, not the 0 we just wrote. This
    // packet is relay-only (the server takes run status from `died` below,
    // never from the stream), and it is the last thing the rival's client
    // hears from us — so if it carried the post-death 0, their pill would
    // snap to 0 and announce the death that oppDied deliberately stays quiet
    // about. Their view freezes on our last live score instead. The server's
    // own record is still zeroed by the `died` handler, so the result is
    // unaffected.
    Net.sendState(true, lost);
    Net.emit('died', {});
    UI.refreshCashout();
    if (Game.solo) setTimeout(function () { UI.showEndSolo(); }, 1300);
  }

  /**
   * CASHOUT. Locks the pending score into banked, ends the run safely, and
   * tells the rival what they now have to beat.
   */
  function bankScore() {
    if (Game.phase !== 'playing' || !Player.isRunning()) return;
    if (Player.pending <= 0) return;

    Player.banked = Player.pending;
    Player.status = 'banked';
    Player.hopping = false;
    Player.queued = null;

    Game.phase = 'resolved';
    Game.resolveAt = Game.t;

    Popups.add('BANKED  ' + Player.banked, PAL.neon, { size: 0.46, vy: 1.0, centre: true, life: 1.5 });
    SFX.cash();
    if (navigator.vibrate) { try { navigator.vibrate([0, 35, 30, 35]); } catch (e) {} }

    H2H.noteBest(Player.banked);

    Net.sendState(true);
    Net.emit('cashout', { p: Player.banked });
    UI.refreshCashout();
    if (Game.solo) setTimeout(function () { UI.showEndSolo(); }, 1400);
  }

